"""Dot-matrix fonts for scrolling text on drone screens.

Two built-in fonts, all drawn on a grid of drones:

* ``LED``   — 5 x 7, thin strokes. Every glyph fits in 7 rows like on an LED sign:
  capitals use all 7, lowercase letters have a 5-row x-height with their tails
  tucked in, capitals with marks (Ö Ü İ Ğ) are 5 rows under their mark.
* ``BLOCK`` — 5 rows, capitals only (lowercase is shown as capitals), blocky.
  Doubled it is 10 x 10 drones per letter with 2-drone strokes: big letters that
  fill a small square screen.

Glyphs are proportional (I, l, 1 are narrow), one empty column between letters.
Covers printable ASCII (BLOCK: letters, digits and common punctuation), Turkish
(Ç Ğ İ Ö Ş Ü ç ğ ı ö ş ü), ° € and a heart (♥ / ❤). Other accented letters fall
back to their base letter (é -> e); anything else shows as '?'. Drawn for this
add-on (GPL-3.0-or-later like the rest of it).

Pure Python + numpy.
"""

