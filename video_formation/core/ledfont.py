_ALIASES = {"❤": "♥", "♡": "♥", "’": "'", "‘": "'", "“": '"', "”": '"', "–": "-", "—": "-", "…": "..."}
#: Characters that never show (variation selectors, zero-width joiners ...).
_INVISIBLE = {"️", "︎", "‍", "​"}


def _bitmap(rows) -> np.ndarray:
    return np.array([[ch == "#" for ch in row] for row in rows], dtype=bool)


def _check(table, rows):
    for ch, glyph_rows in table.items():  # every glyph: `rows` rows of equal width
        assert len(glyph_rows) == rows and len({len(r) for r in glyph_rows}) == 1, ch


_check(_G, 7)
_check(_B, 5)
_LED = {ch: _bitmap(rows) for ch, rows in _G.items()}

#: name -> (rows, glyphs, space width, capitals only)
FONTS = {
    "LED": (7, _LED, 2, False),
    "BLOCK": (5, {ch: _bitmap(rows) for ch, rows in _B.items()}, 2, True),
}
ROWS = 7  # the LED fonts' height (kept for older callers)


def font_rows(font: str = "LED") -> int:
    return FONTS[_font(font)][0]


def _font(font: str) -> str:
    font = str(font).upper()
    return font if font in FONTS else "LED"


def _upper(ch: str) -> str:
    """English capitals (i -> I); the Turkish ı is I too. Type İ for a dotted capital."""
    if ch == "ı":
        return "I"
    return ch.upper() if len(ch.upper()) == 1 else ch


def _lookup(ch: str, font: str):
    rows, table, space, caps = FONTS[font]
    if ch in (" ", "\t", "\u00a0"):
        return np.zeros((rows, space), dtype=bool)
    if caps:
        ch = _upper(ch)
    if ch in table:
        return table[ch]
    base = unicodedata.normalize("NFD", ch)[:1]
    if caps:
        base = _upper(base)
    if base in table:
        return table[base]
    return None


def glyph(ch: str, font: str = "LED") -> np.ndarray:
    """(rows, w) bool. Unknown accented letters use their base letter, else '?'."""
    font = _font(font)
    g = _lookup(ch, font)
    return g if g is not None else FONTS[font][1]["?"]


def supported(ch: str, font: str = "LED") -> bool:
    return ch in _INVISIBLE or _lookup(_ALIASES.get(ch, ch), _font(font)) is not None


def clean_text(text: str) -> str:
    """One line: line breaks become spaces, aliases mapped, invisible marks removed."""
    out = []
    for ch in str(text).replace("\r", " ").replace("\n", " "):
        if ch in _INVISIBLE:
            continue
        out.append(_ALIASES.get(ch, ch))
    return "".join(out)


def render(text: str, font: str = "LED") -> np.ndarray:
    """The whole text as one (rows, W) float strip (1 = lit), glyphs separated by
    ``GAP`` empty columns. An empty text gives a (rows, 0) strip."""
    font = _font(font)
    rows = FONTS[font][0]
    parts = []
    for i, ch in enumerate(clean_text(text)):
        if i:
            parts.append(np.zeros((rows, GAP), dtype=bool))
        parts.append(glyph(ch, font))
    if not parts:
        return np.zeros((rows, 0), dtype=np.float32)
    return np.concatenate(parts, axis=1).astype(np.float32)


def widest(font: str = "LED") -> int:
    return max(b.shape[1] for b in FONTS[_font(font)][1].values())


def unknown_chars(text: str, font: str = "LED") -> list[str]:
    """Characters of ``text`` the font draws as '?'."""
    seen = []
    for ch in clean_text(text):
        if not supported(ch, font) and ch not in seen:
            seen.append(ch)
    return seen
